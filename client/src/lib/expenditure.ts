export interface PensionRow {
  group: string;
  country_name: string;
  pension_contribution_effective_rate_avg_earnings_pct: number | null;
  pension_contribution_nominal_total_pct: number | null;
  net_replacement_rate_100pct_avg_wage_mandatory: number | null;
}
export interface PensionFile {
  source: string;
  rows: PensionRow[];
  source_url?: string;
  notes?: string;
}

export interface RegionalRow {
  geo?: string;
  geo_name: string;
  rpp_all_items_2024?: number | null;
  rpp_goods_2024?: number | null;
  rpp_services_housing_rents_2024?: number | null;
  rpp_services_utilities_2024?: number | null;
  rpp_services_other_2024?: number | null;
  /** Germany: BBSR/IW regional price index, baseline 100. */
  regional_price_index_2022_baseline_100?: number | null;
  housing_owner_share?: number | null;
  group?: string;
}
export interface RegionalFile {
  source: string;
  country: string;
  year: number;
  data_tier: DataTier;
  breakdown: string;
  rows: RegionalRow[];
  source_url?: string;
  notes?: string;
}

/* ------------------------------------------------------------------ manifest */

interface ManifestEntry {
  /** Distribution-shaped file (deciles / quintiles / income brackets). */
  dist: string | null;
  /** By-household-type file, when the survey publishes one. */
  hhType: string | null;
  /** Source values are monthly and must be annualized. */
  monthly?: boolean;
}

export const EXPENDITURE_MANIFEST: Record<V2Country, ManifestEntry> = {
  US: { dist: 'us_ces_2024_by_decile.json', hhType: 'us_ces_2024_by_hhtype.json' },
  DE: { dist: 'de_evs.json', hhType: null, monthly: true },
  UK: { dist: 'uk_lcf.json', hhType: 'uk_lcf_by_hhtype.json' },
  JP: { dist: 'jp_fies.json', hhType: null },
  CH: { dist: 'ch_habe.json', hhType: null },
  FI: { dist: 'fi_hbs.json', hhType: null },
  NO: { dist: 'no_expenditure.json', hhType: null },
  SE: { dist: 'se_expenditure.json', hhType: null },
};

export function v2DataUrl(file: string): string {
  return new URL(`./data/v2/${file}`, document.baseURI).toString();
}

async function getJson<T>(file: string): Promise<T | null> {
  try {
    const res = await fetch(v2DataUrl(file));
    if (!res.ok) return null;
    return (await res.json()) as T;
  } catch {
    return null;
  }
}

/* -------------------------------------------------------------- placeholders */

/**
 * Placeholder rows, used only when a real file is unavailable.
 *
 * Shape and levels come from published **BLS Consumer Expenditure Survey** aggregates
 * (https://www.bls.gov/cex/tables.htm): average annual expenditures per consumer unit of
 * about $77k with housing ≈33%, transport ≈17%, food ≈13%, healthcare ≈8%, entertainment
 * ≈5%, apparel ≈3%. Deciles are generated by scaling those shares along a spending gradient
 * that flattens at the top (spending rises much more slowly than income).
 */
const MOCK_SHARES: Record<CategoryKey, number> = {
  housing: 0.33,
  food_at_home: 0.078,
  food_away: 0.05,
  healthcare_oop: 0.08,
  transport_work: 0.115,
  transport_total: 0.17,
  apparel: 0.026,
  communications: 0.021,
  personal_care: 0.012,
  education: 0.017,
  childcare: 0.011,
  voluntary_savings: 0.07,
  entertainment: 0.048,
  cash_contributions: 0.028,
  other: 0.06,
};

/** Rough level factor so a placeholder country lands in its own currency ballpark. */
const MOCK_LEVEL: Record<V2Country, number> = {
  US: 1,
  DE: 0.62,
  UK: 0.6,
  NO: 9.0,
  SE: 8.6,
  FI: 0.6,
  CH: 1.05,
  JP: 78,
};

export function mockExpenditure(country: V2Country): ExpenditureDataset {
  const level = MOCK_LEVEL[country] ?? 1;
  const baseTotal = 77000 * level;
  const rows: ExpenditureRow[] = [];
  for (let k = 1; k <= 10; k++) {
    // Spending gradient: bottom decile ≈0.42× the mean, top ≈2.0×, concave in between.
    const t = (k - 0.5) / 10;
    const grad = 0.42 + 1.58 * Math.pow(t, 1.35);
    const total = baseTotal * grad;
    const cats: Partial<Record<CategoryKey, number>> = {};
    (Object.keys(MOCK_SHARES) as CategoryKey[]).forEach((c) => {
      // Necessities are less elastic than the average, savings much more.
      const elasticity =
        c === 'voluntary_savings' ? 1.9 : c === 'food_at_home' || c === 'healthcare_oop' ? 0.62 : c === 'housing' ? 0.8 : 1;
      cats[c] = Math.round(baseTotal * MOCK_SHARES[c] * Math.pow(grad, elasticity));
    });
    rows.push({
      group: `d${k}`,
      avg_income_before_tax: Math.round(baseTotal * (0.16 + 2.6 * Math.pow(t, 1.9))),
      avg_income_after_tax: null,
      avg_expenditure_total: Math.round(total),
      expenditure_by_category: cats,
      housing_owner_share: Math.min(0.9, 0.3 + 0.55 * t),
      housing_owner_imputed_rent_estimate: Math.round(baseTotal * MOCK_SHARES.housing * 0.66 * Math.pow(grad, 0.8)),
    });
  }
  return {
    source: 'Placeholder — scaled from published BLS Consumer Expenditure Survey aggregates',
    country,
    year: 2024,
    unit: country === 'US' ? 'USD' : 'local',
    price_basis: 'placeholder',
    data_tier: 'C',
    breakdown: 'by_decile',
    rows,
    source_url: 'https://www.bls.gov/cex/tables.htm',
    notes:
      'Synthetic placeholder rows generated from published CES category shares. Not a survey result — every figure derived from them is badged Placeholder.',
    placeholder: true,
  };
}

/* ------------------------------------------------------------------- loading */

function annualize(ds: ExpenditureDataset, monthly: boolean): ExpenditureDataset {
  if (!monthly) return ds;
  const mul = (v: number | null | undefined) => (typeof v === 'number' && Number.isFinite(v) ? v * 12 : null);
  return {
    ...ds,
    rows: ds.rows.map((r) => {
      const cats: Partial<Record<CategoryKey, number | null>> = {};
      for (const [k, v] of Object.entries(r.expenditure_by_category ?? {})) {
        cats[k as CategoryKey] = mul(v as number | null);
      }
      return {
        ...r,
        avg_income_before_tax: mul(r.avg_income_before_tax),
        avg_income_after_tax: mul(r.avg_income_after_tax),
        avg_expenditure_total: mul(r.avg_expenditure_total),
        expenditure_by_category: cats,
        housing_owner_imputed_rent_estimate: mul(r.housing_owner_imputed_rent_estimate),
      };
    }),
    notes: `${ds.notes ?? ''} Monthly source values annualized ×12 by the client.`.trim(),
  };
}

/**
 * A file is only usable if it actually carries expenditure levels. Norway and Sweden ship
 * income-side rows with `avg_expenditure_total: null` and no categories (their expenditure
 * surveys were discontinued in 2012 and 2009) — those must fall through to placeholders
 * rather than silently rendering zeros. See data/v2/README.md.
 */
function usable(ds: ExpenditureDataset | null): boolean {
  if (!ds || !Array.isArray(ds.rows) || ds.rows.length === 0) return false;
  return ds.rows.some(
    (r) =>
      (typeof r.avg_expenditure_total === 'number' && Number.isFinite(r.avg_expenditure_total)) ||
      Object.values(r.expenditure_by_category ?? {}).some((v) => typeof v === 'number' && Number.isFinite(v))
  );
}

export interface CountryExpenditure {
  dist: ExpenditureDataset;
  hhType: ExpenditureDataset | null;
  /** True when `dist` is a real published survey. */
  real: boolean;
}

export async function loadExpenditure(country: V2Country): Promise<CountryExpenditure> {
  const entry = EXPENDITURE_MANIFEST[country];
  const [distRaw, hhRaw] = await Promise.all([
    entry.dist ? getJson<ExpenditureDataset>(entry.dist) : Promise.resolve(null),
    entry.hhType ? getJson<ExpenditureDataset>(entry.hhType) : Promise.resolve(null),
  ]);
  const dist = usable(distRaw) ? annualize(distRaw as ExpenditureDataset, !!entry.monthly) : mockExpenditure(country);
  const hhType = usable(hhRaw) ? annualize(hhRaw as ExpenditureDataset, !!entry.monthly) : null;
  return { dist: { ...dist, country }, hhType: hhType ? { ...hhType, country } : null, real: usable(distRaw) };
}

export interface V2Store {
  expenditure: Partial<Record<V2Country, CountryExpenditure>>;
  studentLoans: StudentLoanFile | null;
  pensions: PensionFile | null;
  rppState: RegionalFile | null;
  rppMetro: RegionalFile | null;
  laender: RegionalFile | null;
  /** Countries whose expenditure file loaded for real. */
  realCountries: V2Country[];
  placeholderCountries: V2Country[];
}

export const V2_LOADED_COUNTRIES: V2Country[] = ['US', 'DE', 'UK', 'JP', 'CH', 'FI', 'NO', 'SE'];

export async function loadV2(): Promise<V2Store> {
  const [studentLoans, pensions, rppState, rppMetro, laender, ...perCountry] = await Promise.all([
    getJson<StudentLoanFile>('us_scf_studentloans.json'),
    getJson<PensionFile>('oecd_pensions.json'),
    getJson<RegionalFile>('us_rpp_state.json'),
    getJson<RegionalFile>('us_rpp_metro.json'),
    getJson<RegionalFile>('de_laender_costs.json'),
    ...V2_LOADED_COUNTRIES.map((c) => loadExpenditure(c)),
  ]);
  const expenditure: Partial<Record<V2Country, CountryExpenditure>> = {};
  V2_LOADED_COUNTRIES.forEach((c, i) => {
    expenditure[c] = perCountry[i];
  });
  return {
    expenditure,
    studentLoans,
    pensions,
    rppState,
    rppMetro,
    laender,
    realCountries: V2_LOADED_COUNTRIES.filter((c) => expenditure[c]?.real),
    placeholderCountries: V2_LOADED_COUNTRIES.filter((c) => !expenditure[c]?.real),
  };
}

/* --------------------------------------------------- row lookup by percentile */

/** Rank midpoint (0–1) of a distribution row. */
function rankOf(group: string, index: number, n: number): number {
  const d = /^d(\d+)$/.exec(group);
  if (d) return (Number(d[1]) - 0.5) / 10;
  const q = /^q(\d+)$/.exec(group);
  if (q) return (Number(q[1]) - 0.5) / 5;
  // Income brackets with no published population weights: assume equal population shares.
  return (index + 0.5) / Math.max(n, 1);
}

export interface InterpolatedRow extends ExpenditureRow {
  /** Provenance of the interpolation, before any modeling downstream. */
  provenance: V2Provenance;
  /** Rank position used for the lookup. */
  rank: number;
  /** Human-readable anchor description, e.g. "between d5 and d6". */
  anchorNote: string;
}

const NUMERIC_CATS = Object.keys(MOCK_SHARES) as CategoryKey[];

function catOf(row: ExpenditureRow, c: CategoryKey): number | null {
  const v = row.expenditure_by_category?.[c];
  return typeof v === 'number' && Number.isFinite(v) ? v : null;
}

/**
 * Read the expenditure profile at an arbitrary percentile by interpolating linearly in
 * rank space between the published group anchors. Below the first anchor and above the
 * last the nearest anchor is held flat (surveys do not publish beyond their own groups).
 */
export function rowAtPercentile(ds: ExpenditureDataset, p: number): InterpolatedRow {
  const anchors = ds.rows.map((r, i) => ({ row: r, rank: rankOf(r.group, i, ds.rows.length) })).sort((a, b) => a.rank - b.rank);
  const clamped = Math.min(Math.max(p, 0.001), 0.999);
  const base: V2Provenance = ds.placeholder ? 'placeholder' : 'published';

  if (anchors.length === 0) {
    return { ...mockExpenditure(ds.country).rows[4], provenance: 'placeholder', rank: clamped, anchorNote: 'no rows' };
  }
  if (clamped <= anchors[0].rank) {
    return { ...anchors[0].row, provenance: base, rank: clamped, anchorNote: `${anchors[0].row.group} (lowest published group)` };
  }
  const last = anchors[anchors.length - 1];
  if (clamped >= last.rank) {
    return { ...last.row, provenance: base, rank: clamped, anchorNote: `${last.row.group} (highest published group)` };
  }
  let hi = 1;
  while (hi < anchors.length && anchors[hi].rank < clamped) hi++;
  const a = anchors[hi - 1];
  const b = anchors[hi];
  const t = (clamped - a.rank) / (b.rank - a.rank || 1);
  const lerp = (x: number | null, y: number | null): number | null => {
    if (x === null && y === null) return null;
    if (x === null) return y;
    if (y === null) return x;
    return x + (y - x) * t;
  };
  const cats: Partial<Record<CategoryKey, number | null>> = {};
  for (const c of NUMERIC_CATS) cats[c] = lerp(catOf(a.row, c), catOf(b.row, c));
  const exact = t < 0.02 || t > 0.98;
  return {
    group: `${a.row.group}→${b.row.group}`,
    avg_income_before_tax: lerp(a.row.avg_income_before_tax, b.row.avg_income_before_tax),
    avg_income_after_tax: lerp(a.row.avg_income_after_tax, b.row.avg_income_after_tax),
    avg_expenditure_total: lerp(a.row.avg_expenditure_total, b.row.avg_expenditure_total),
    expenditure_by_category: cats,
    housing_owner_share: lerp(a.row.housing_owner_share, b.row.housing_owner_share),
    housing_owner_imputed_rent_estimate: lerp(a.row.housing_owner_imputed_rent_estimate, b.row.housing_owner_imputed_rent_estimate),
    provenance: ds.placeholder ? 'placeholder' : exact ? 'published' : 'interpolated',
    rank: clamped,
    anchorNote: `between ${a.row.group} and ${b.row.group}`,
  };
}

/** Annualized minimum student-loan payment at a given percentile (US only). */
export function studentLoanPayment(file: StudentLoanFile | null, country: V2Country, p: number): { amount: number; provenance: V2Provenance; note: string } {
  if (country !== 'US' || !file || !file.rows?.length) {
    return {
      amount: 0,
      provenance: 'published',
      note:
        'In countries with tuition-free higher education (Norway, Sweden, Finland, Germany) this line is near zero — a real feature of the comparison, not a data gap. The UK repays income-contingently above a threshold and is not modeled here.',
    };
  }
  const anchors = file.rows
    .map((r, i) => ({ r, rank: rankOf(r.group, i, file.rows.length) }))
    .sort((a, b) => a.rank - b.rank);
  const clamped = Math.min(Math.max(p, 0.001), 0.999);
  let hi = 1;
  while (hi < anchors.length && anchors[hi].rank < clamped) hi++;
  const a = anchors[Math.max(hi - 1, 0)];
  const b = anchors[Math.min(hi, anchors.length - 1)];
  const t = b.rank === a.rank ? 0 : (clamped - a.rank) / (b.rank - a.rank);
  const bal = (x: StudentLoanRow) => x.student_loan_mean_balance_all_families ?? 0;
  const balance = bal(a.r) + (bal(b.r) - bal(a.r)) * Math.min(Math.max(t, 0), 1);
  // Standard 10-year amortization at 5.5% nominal → 0.1302 of principal per year.
  const AMORT = 0.1302;
  return {
    amount: balance * AMORT,
    provenance: 'modeled',
    note:
      'Fed SCF 2022 mean student-loan balance across all families at this income position, amortized over the standard 10-year federal repayment plan at 5.5% (factor 0.1302/yr).',
  };
}

export function pensionRate(file: PensionFile | null, country: V2Country): { pct: number | null; note: string } {
  const row = file?.rows?.find((r) => r.group === country);
  if (!row) return { pct: null, note: 'Mandatory pension contribution rate not loaded for this country.' };
  const pct = row.pension_contribution_effective_rate_avg_earnings_pct ?? row.pension_contribution_nominal_total_pct ?? null;
  return {
    pct,
    note: `Mandatory pension: ${pct === null ? '—' : `${pct.toFixed(1)}%`} of average earnings (already excluded from DINA post-tax income). Net mandatory replacement rate ${
      row.net_replacement_rate_100pct_avg_wage_mandatory ?? '—'
    }%.`,
  };
}

export function tierLabel(t: DataTier): string {
  if (t === 'A') return 'Tier A — recent annual survey';
  if (t === 'B') return 'Tier B — interpolated from a multi-year survey';
  return 'Tier C — modeled from register data or placeholders';
}
